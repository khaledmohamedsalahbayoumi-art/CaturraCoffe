// Helper: Localize Tasting Notes / Description
export const getLocalizedNotes = (item, lang = 'ar') => {
  if (!item) return '';
  if (typeof item === 'string') {
    if (lang !== 'en') return item;
    let res = item;
    for (const n of notesTerms) {
      res = res.replace(new RegExp(n.ar, 'g'), n.en);
    }
    return res;
  }
  if (lang === 'en') {
    if (item.tastingNotesEn || item.notesEn) {
      return item.tastingNotesEn || item.notesEn;
    }
    const raw = item.notes || item.tastingNotes || item.description || '';
    let res = raw;
    for (const n of notesTerms) {
      res = res.replace(new RegExp(n.ar, 'g'), n.en);
    }
    return res;
  }
  return item.notes || item.tastingNotes || item.description || '';
};

