export const getLocalizedRoast = (roastText, lang = 'ar') => {
  if (!roastText) return '';
  const text = typeof roastText === 'object' ? (roastText.roastLevel || roastText.roast || '') : String(roastText);
  if (!text) return '';
  const lower = text.toLowerCase().trim();
  
  if (lang === 'en') {
    for (const item of roastTerms) {
      if (text.includes(item.ar) || (item.matchEn && item.matchEn.some(m => lower === m || lower.includes(m)))) {
        return item.en;
      }
    }
    return text.includes('Roast') ? text : `${text} Roast`;
  }

  // Arabic
  for (const item of roastTerms) {
    if ((item.matchEn && item.matchEn.some(m => lower === m || lower.includes(m))) || text.includes(item.en)) {
      return item.ar;
    }
    if (text.includes(item.ar)) {
      return item.ar;
    }
  }
  return text;
};

